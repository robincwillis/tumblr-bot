import path from 'node:path';
import crypto from 'node:crypto';
import { mimeFor } from './local.js';

/**
 * Dropbox source. config:
 *   { type: "dropbox", path: "/Life/Photos",           // folder to index ("" = whole Dropbox)
 *     refreshToken, appKey, appSecret }                 // recommended: never expires
 *   or { accessToken }                                  // short-lived; fine for trying it out
 * Create an app at dropbox.com/developers/apps with scopes files.metadata.read +
 * files.content.read. Tags come from folder names, same as local sources.
 */
export class DropboxSource {
  constructor(name, cfg) {
    const refresh = cfg.refreshToken && cfg.appKey && cfg.appSecret;
    if (!refresh && !cfg.accessToken) {
      throw new Error(`source "${name}" (dropbox): give accessToken, or refreshToken + appKey + appSecret`);
    }
    this.name = name;
    this.cfg = cfg;
    this.root = (cfg.path ?? '').replace(/\/$/, '');
    this.token = cfg.accessToken;
    this.tokenExpires = cfg.accessToken ? Infinity : 0;
  }

  async #accessToken(force = false) {
    if (!force && this.token && Date.now() < this.tokenExpires - 60_000) return this.token;
    if (!this.cfg.refreshToken) throw new Error('Dropbox access token rejected and no refreshToken configured');
    const res = await fetch('https://api.dropboxapi.com/oauth2/token', {
      method: 'POST',
      body: new URLSearchParams({
        grant_type: 'refresh_token', refresh_token: this.cfg.refreshToken,
        client_id: this.cfg.appKey, client_secret: this.cfg.appSecret,
      }),
    });
    if (!res.ok) throw new Error(`Dropbox token refresh: ${res.status} ${await res.text()}`);
    const j = await res.json();
    this.token = j.access_token;
    this.tokenExpires = Date.now() + j.expires_in * 1000;
    return this.token;
  }

  /** Authenticated fetch with one token refresh on 401 and Retry-After handling on 429. */
  async #fetch(url, init, { attempt = 0, forceToken = false } = {}) {
    const res = await fetch(url, { ...init, headers: { ...init.headers, Authorization: `Bearer ${await this.#accessToken(forceToken)}` } });
    if (res.status === 401 && !forceToken && this.cfg.refreshToken) return this.#fetch(url, init, { attempt, forceToken: true });
    if (res.status === 429 && attempt < 4) {
      await new Promise((r) => setTimeout(r, Number(res.headers.get('retry-after') ?? 1) * 1000));
      return this.#fetch(url, init, { attempt: attempt + 1 });
    }
    if (!res.ok) throw new Error(`Dropbox ${new URL(url).pathname}: ${res.status} ${await res.text()}`);
    return res;
  }

  #rpc(endpoint, body) {
    return this.#fetch(`https://api.dropboxapi.com/2/${endpoint}`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
    }).then((r) => r.json());
  }

  async list({ fileTypes }) {
    const out = [];
    let page = await this.#rpc('files/list_folder', { path: this.root, recursive: true, limit: 2000 });
    for (;;) {
      for (const e of page.entries) {
        if (e['.tag'] !== 'file') continue;
        const mime = mimeFor(e.name);
        if (!mime || (fileTypes && !fileTypes.includes(mime))) continue;
        const rel = e.path_display.slice(this.root.length).replace(/^\//, '');
        if (rel.split('/').some((seg) => seg.startsWith('.'))) continue;
        const folder = path.posix.dirname(rel) === '.' ? '' : path.posix.dirname(rel);
        out.push({
          id: crypto.createHash('sha1').update(`${this.name}:${rel}`).digest('hex').slice(0, 16),
          source: this.name, path: rel, name: e.name, mime, size: e.size,
          modified: e.client_modified ?? e.server_modified,
          version: e.content_hash ?? e.rev,
          folder, tags: folder ? folder.toLowerCase().split('/') : [],
        });
      }
      if (!page.has_more) break;
      page = await this.#rpc('files/list_folder/continue', { cursor: page.cursor });
    }
    return out;
  }

  // Dropbox-API-Arg is an HTTP header: non-ASCII must be \u-escaped.
  static #arg = (o) => JSON.stringify(o).replace(/[\u007f-￿]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
  #remote(asset) { return `${this.root}/${asset.path}`; }

  async read(asset) {
    const res = await this.#fetch('https://content.dropboxapi.com/2/files/download', {
      method: 'POST', headers: { 'Dropbox-API-Arg': DropboxSource.#arg({ path: this.#remote(asset) }) },
    });
    return Buffer.from(await res.arrayBuffer());
  }

  /** Small JPEG rendition generated by Dropbox — far cheaper than downloading originals to embed them. */
  async thumbnail(asset) {
    const res = await this.#fetch('https://content.dropboxapi.com/2/files/get_thumbnail_v2', {
      method: 'POST',
      headers: { 'Dropbox-API-Arg': DropboxSource.#arg({ resource: { '.tag': 'path', path: this.#remote(asset) }, format: 'jpeg', size: 'w480h320' }) },
    });
    return Buffer.from(await res.arrayBuffer());
  }
}
